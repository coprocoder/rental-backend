/**
 * Дедлайн подтверждения брони.
 *
 * Механизм из ТЗ (../rental-docs/docs/04-тз/10-бэкенд/12-наличие-и-жизненный-цикл.md):
 * бронь живёт не «до даты», а до дедлайна подтверждения. Не подтвердил —
 * инвентарь возвращается в пул. Это защита от блокировки арсенала,
 * которая работает без предоплаты: удержать 30 бордов стоит 30
 * подтверждений, а невозвратные брони в РФ незаконны.
 *
 * Два правила, и они РАЗНЫЕ:
 *
 *   бронь на будущие даты — подтвердить за сутки до начала, иначе
 *                           снимается автоматически;
 *   бронь на сегодня      — автоснятия НЕТ вовсе, инвентарь держится,
 *                           снять может только оператор вручную.
 *
 * ⚠️ Критерий второго правила — «сегодня по календарю филиала», а НЕ
 * «меньше суток до начала». Разница видна на брони, оформленной сегодня
 * в 16:00 на завтра в 10:00: суток до начала нет, но и «сегодня» это не
 * является — человек ещё не едет, и такая бронь должна сниматься, иначе
 * она заблокирует инвентарь навсегда.
 *
 * Почему для сегодняшних броней автоматики нет: человек уже в пути,
 * связи может не быть, и автоснятие вредит больше, чем помогает.
 * Ответственность за них несёт оператор, который видит очередь.
 */
import { localDayNumber } from '~/common/contract/day-count'

/**
 * Сколько времени до начала аренды даётся на подтверждение по умолчанию.
 *
 * ⚠️ Значение по умолчанию, а не константа поведения: тенант меняет его
 * через booking_limit.confirm_deadline_hours. Правило «за сутки» человек
 * понимает без объяснений, поэтому оно и выбрано дефолтом.
 */
export const CONFIRM_LEAD_MS = 24 * 3600 * 1000

/**
 * Минимальное окно на подтверждение для брони, оформленной позже чем
 * за сутки до начала (но не на сегодня).
 *
 * ⚠️ Нужно именно окно, а не «дедлайн = сейчас»: дедлайн в момент
 * оформления истекает мгновенно, и автоснятие убирает заказ сразу
 * после того, как клиент увидел подтверждение. Два часа — время
 * прочитать письмо и нажать ссылку.
 */
export const MIN_CONFIRM_WINDOW_MS = 2 * 3600 * 1000

/**
 * @param from      начало аренды
 * @param timezone  пояс ФИЛИАЛА: «сегодня» считается по нему, а не по
 *                  поясу сервера или браузера клиента
 * @param now       момент оформления
 * @returns дата дедлайна, либо null — если автоснятия быть не должно
 *          (бронь на сегодня: снимает только оператор)
 */
export function confirmDeadline(
  from: Date,
  timezone: string,
  now: Date = new Date(),
  /** Настройка тенанта booking_limit.confirm_deadline_hours. */
  leadHours = 24,
): Date | null {
  // Бронь на сегодня — автоснятия нет.
  if (localDayNumber(from, timezone) === localDayNumber(now, timezone)) {
    return null
  }

  const deadline = new Date(from.getTime() - leadHours * 3600 * 1000)

  // ⚠️ Дедлайн не может быть в прошлом и не может истекать мгновенно:
  // иначе автоснятие убирает заказ сразу после оформления. Для брони,
  // оформленной позже чем за сутки до начала, даётся минимальное окно —
  // но не позже самого начала аренды: подтверждать уехавшую бронь незачем.
  const floor = Math.min(now.getTime() + MIN_CONFIRM_WINDOW_MS, from.getTime())
  return deadline.getTime() > floor ? deadline : new Date(floor)
}
