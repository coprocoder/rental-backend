/**
 * Расчёт рекомендованного DIN.
 *
 * ⚠️ Это НАРЯД ДЛЯ ТЕХНИКА, а не значение для клиента (железное
 * правило №7). Система считает рекомендацию; фактически выставленное
 * значение и подпись техника пишутся в заказ отдельно — это след
 * ответственности, и заменить его расчётом нельзя.
 *
 * Правовой контур (../rental-docs/docs/04-тз/00-общее/04-правовое.md):
 *   ISO 11088 применяется к аренде ≥15 дней; для основного потока
 *   проката действует ISO 13993 — выборочный контроль партий, а не
 *   тест на каждого клиента;
 *   ни один стандарт и ни одно известное дело не возлагают
 *   ответственность на разработчика ПО: расчёт поставляется как
 *   рекомендация, ответственность на прокате и технике.
 *
 * ⚠️ Результат расчёта — КОД A–P и диапазон шкалы, а не точное число.
 * Почему не число — подробно у CODE_RANGES: переход от момента ISO к
 * значению шкалы задаётся таблицей конкретного крепления, и «примерная»
 * цифра здесь опаснее её отсутствия, потому что техник ей доверится.
 *
 * ⚠️ Версия года чартов обязательна и пишется в заказ: ASTM отменил
 * поправочные коэффициенты около трёх лет назад, и расчёт по старым
 * правилам со временем становится неверным. Без версии невозможно
 * понять, по каким правилам считали прошлый сезон.
 */

/** Версия чартов. Меняется вместе с формулами, пишется в заказ. */
export const DIN_CHART_VERSION = 'iso-8061:2019'

export interface DinInput {
  /** Вес, кг — ведущий параметр. */
  weight: number
  /** Рост, см — ограничивает код сверху для тяжёлых кодов. */
  height?: number
  age?: number
  /** Длина подошвы ботинка, мм. Читается со штампа при выдаче. */
  bslMm?: number
}

export interface DinResult {
  /** Код навыка A–P по ISO — это и есть результат расчёта. */
  code: string
  /**
   * Диапазон шкалы для этого кода.
   *
   * ⚠️ Диапазон, а НЕ точка: переход от момента ISO к значению шкалы
   * задаётся таблицей конкретного крепления. Точную цифру выставляет
   * техник, система лишь сужает поиск и ловит грубые ошибки.
   */
  range: [number, number] | null
  chartVersion: string
  /** Почему получился такой код — техник должен видеть основание. */
  why: string[]
  /** Чего не хватает для расчёта. */
  missing: string[]
  /** Куда двигаться внутри диапазона с учётом подошвы. */
  bslHint: string | null
}

/**
 * Коды по весу.
 *
 * Границы из ISO 8061; последовательность кодов A…P.
 */
const WEIGHT_CODES: { maxKg: number, code: string }[] = [
  { maxKg: 13, code: 'A' },
  { maxKg: 16, code: 'B' },
  { maxKg: 20, code: 'C' },
  { maxKg: 25, code: 'D' },
  { maxKg: 30, code: 'E' },
  { maxKg: 35, code: 'F' },
  { maxKg: 41, code: 'G' },
  { maxKg: 48, code: 'H' },
  { maxKg: 57, code: 'I' },
  { maxKg: 66, code: 'J' },
  { maxKg: 78, code: 'K' },
  { maxKg: 94, code: 'L' },
  { maxKg: Infinity, code: 'M' },
]

/**
 * Ограничение кода по росту.
 *
 * ⚠️ Для кодов H–M сверяется с ростом, и берётся МЕНЬШИЙ из двух:
 * тяжёлый подросток не должен получить взрослую затяжку.
 */
const HEIGHT_CODES: { maxCm: number, code: string }[] = [
  { maxCm: 148, code: 'H' },
  { maxCm: 157, code: 'I' },
  { maxCm: 166, code: 'J' },
  { maxCm: 178, code: 'K' },
  { maxCm: 194, code: 'L' },
  { maxCm: Infinity, code: 'M' },
]

const ORDER = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M', 'N', 'O', 'P']

function codeIndex(code: string): number {
  return ORDER.indexOf(code)
}

/**
 * Диапазон шкалы по коду и длине подошвы.
 *
 * ⚠️ ЗДЕСЬ НЕТ ФОРМУЛЫ, И ЭТО СОЗНАТЕЛЬНО. Первая версия этого модуля
 * содержала аппроксимацию вида `0.75 · 1.3^(idx·0.62)` с поправкой на
 * BSL. Проверка на контрольных точках показала занижение в 1.5–2 раза:
 * для взрослого 75 кг с подошвой 300 мм выходило 4.0 вместо ожидаемых
 * 6.0–7.0. Заниженный DIN — это самопроизвольное отстёгивание лыжи на
 * скорости, то есть травма.
 *
 * Формула Mz = 0.84·ms + 4 из ISO 8061 даёт МОМЕНТ закручивания, а не
 * значение шкалы; переход от момента к шкале задаётся таблицей
 * производителя крепления и от модели зависит. Вывести его «примерно»
 * нельзя — точнее, можно, но результат будет неверным, а неверный DIN
 * хуже отсутствующего: техник доверится числу.
 *
 * Поэтому модуль отдаёт КОД и диапазон, в котором значение находится
 * заведомо, а конкретную цифру техник берёт из таблицы своего
 * крепления. Это и соответствует роли системы: наряд для техника,
 * а не готовое значение (железное правило №7).
 *
 * Диапазоны — консервативные границы кодов из открытых чартов
 * (публикуются производителями, например Fischer). Внутри диапазона
 * значение зависит от подошвы: чем ДЛИННЕЕ подошва, тем НИЖЕ затяжка —
 * больше рычаг, тот же момент достигается меньшим значением. Это
 * самая частая ошибка самодельных калькуляторов, поэтому направление
 * поправки указывается технику явно.
 */
const CODE_RANGES: Record<string, [number, number]> = {
  A: [0.75, 0.75],
  B: [0.75, 1.0],
  C: [1.0, 1.5],
  D: [1.5, 2.0],
  E: [1.75, 2.5],
  F: [2.0, 3.0],
  G: [2.5, 3.5],
  H: [3.0, 4.5],
  I: [3.5, 5.5],
  J: [4.5, 6.5],
  K: [5.5, 8.0],
  L: [7.0, 10.0],
  M: [8.5, 11.5],
  N: [10.0, 13.0],
  O: [11.5, 15.0],
  P: [13.0, 16.0],
}

/**
 * ⚠️ Возвращает НЕ точку, а диапазон: точное значение зависит от
 * таблицы конкретного крепления, и подставлять середину диапазона
 * значило бы выдавать догадку за расчёт.
 */
function rangeFor(code: string): [number, number] | null {
  return CODE_RANGES[code] ?? null
}

/**
 * Рекомендованный DIN.
 *
 * ⚠️ Тип катания НЕ спрашивается и сдвиг по нему не применяется: код
 * фиксирован на Тип I (консервативно). Уровень катания — субъективная
 * самооценка, а ошибка в сторону более сильной затяжки опаснее.
 */
export function recommendDin(input: DinInput): DinResult {
  const why: string[] = []
  const missing: string[] = []

  if (!input.weight) {
    return {
      code: '—',
      range: null,
      chartVersion: DIN_CHART_VERSION,
      why: [],
      missing: ['вес'],
      bslHint: null,
    }
  }

  let code = WEIGHT_CODES.find((w) => input.weight <= w.maxKg)?.code ?? 'M'
  why.push(`код ${code} по весу ${input.weight} кг`)

  // Ограничение по росту для старших кодов.
  if (input.height && codeIndex(code) >= codeIndex('H')) {
    const byHeight = HEIGHT_CODES.find((h) => input.height! <= h.maxCm)?.code ?? 'M'
    if (codeIndex(byHeight) < codeIndex(code)) {
      why.push(`понижен до ${byHeight}: рост ${input.height} см (берётся меньший из двух)`)
      code = byHeight
    }
  } else if (!input.height && codeIndex(code) >= codeIndex('H')) {
    missing.push('рост')
  }

  // Возраст: младше 10 или старше 50 — на шаг к A.
  if (input.age !== undefined && (input.age < 10 || input.age > 50)) {
    const idx = codeIndex(code)
    if (idx > 0) {
      code = ORDER[idx - 1]!
      why.push(`понижен на шаг: возраст ${input.age}`)
    }
  }

  why.push('тип катания I (консервативно): уровень не спрашивается')

  // BSL нужен не для кода, а для выбора точки внутри диапазона.
  let bslHint: string | null = null
  if (input.bslMm) {
    bslHint = input.bslMm >= 315
      ? `подошва ${input.bslMm} мм — длинная: значение ближе к НИЖНЕЙ границе диапазона`
      : input.bslMm <= 285
        ? `подошва ${input.bslMm} мм — короткая: значение ближе к ВЕРХНЕЙ границе`
        : `подошва ${input.bslMm} мм — средняя: середина диапазона`
  } else {
    missing.push('BSL (длина подошвы, со штампа на ботинке)')
  }

  return {
    code,
    range: rangeFor(code),
    chartVersion: DIN_CHART_VERSION,
    why,
    missing,
    bslHint,
  }
}

/**
 * Нужна ли wide-доска.
 *
 * ⚠️ Это ЖЁСТКИЙ фильтр, а не предпочтение (../rental-docs/docs/04-тз/00-общее/03-домен.md):
 * от EU 44 нога свисает за кант, носок или пятка цепляют склон при
 * закантовке, и это падение, а не неудобство.
 */
export function needsWideBoard(shoeSizeEu?: number): boolean {
  if (!shoeSizeEu) return false
  return shoeSizeEu >= 44
}

/**
 * Отфильтровывает доски, не подходящие по ширине талии.
 *
 * Возвращает подходящие и причину отсева — клиент должен понимать,
 * почему часть размеров недоступна.
 */
export function filterByWaistWidth<T extends { code: string, attrs?: Record<string, unknown> }>(
  variants: T[],
  shoeSizeEu?: number,
): { fitting: T[], excluded: { code: string, why: string }[] } {
  if (!needsWideBoard(shoeSizeEu)) return { fitting: variants, excluded: [] }

  const fitting: T[] = []
  const excluded: { code: string, why: string }[] = []

  for (const v of variants) {
    const waist = Number(v.attrs?.waistWidthMm ?? 0)
    // Порог 255 мм: ниже него нога от EU 44 свисает за кант.
    if (!waist || waist >= 255) {
      fitting.push(v)
    } else {
      excluded.push({
        code: v.code,
        why: `талия ${waist} мм узка для размера ${shoeSizeEu}: нога заденет склон`,
      })
    }
  }

  // ⚠️ Если подходящих не осталось, возвращаем всё: отказать клиенту
  // совсем хуже, чем предупредить. Решение — за стойкой, у которой
  // доска в руках.
  return fitting.length ? { fitting, excluded } : { fitting: variants, excluded }
}
