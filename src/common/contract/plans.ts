/** Что тариф добавляет по сравнению с предыдущим — для сравнения на экране. */
export function featuresAddedBy(code: string): readonly PlanFeature[] {
  const idx = PLANS.findIndex((p) => p.code === code)
  if (idx <= 0) return PLANS[idx]?.features ?? []
  const prev = new Set(PLANS[idx - 1]!.features)
  return PLANS[idx]!.features.filter((f) => !prev.has(f))
}
