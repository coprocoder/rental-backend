/**
 * Тарифы: состав, отличия и описания — единственный источник правды
 * для фронта и бэка.
 *
 * Спека: ../rental-docs/docs/04-тз/00-общее/06-защита-продукта.md
 *
 * ⚠️ Лежит в `shared/` по той же причине, что и права: нужен ОБЕИМ
 * сторонам. Сервер решает доступ, меню и экран тарифов решают, что
 * показать. Вторая копия описаний во фронте разошлась бы с проверками
 * на первой же правке — и тогда прокат видит функцию в списке тарифа,
 * а сервер её не даёт.
 *
 * ⚠️ Тарифицируется МАСШТАБ И УДОБСТВО, а не возможность работать.
 * Приём заказов, выдача, возврат, смена, прайс и клиенты целиком в
 * базовом тарифе: прокат, купивший подписку, обязан работать.
 *
 * ⚠️ Состав демонстрационный и будет пересобран с заказчиком. Поэтому
 * тариф переключается прямо в админке — отличия надо видеть, а не
 * читать.
 */

/** Функции, которые тариф включает или выключает. */
export type PlanFeature =
  /** Единицы инвентаря с номером и QR, сканирование, история вещи. */
  | 'labeledInventory'
  /** Несколько филиалов: сеть, а не одна точка. */
  | 'multiBranch'
  /**
   * Расширенные настройки склада: расписание, массовые операции,
   * точечные отключения, работа без связи.
   */
  | 'advancedInventory'
  /** Отчёты, сводка «Сегодня», выгрузки. */
  | 'analytics'
  /** Тема, тексты, таблицы подбора. */
  | 'branding'
  /** Роли администратора и техника: работу можно делегировать. */
  | 'delegatedRoles'
  /** Ключи pk_/sk_ для виджета и интеграций. */
  | 'apiAccess'

