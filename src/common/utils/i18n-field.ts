/**
 * Переводимые поля данных (8.7).
 *
 * ⚠️ Названия категорий, вариантов и услуг хранятся в jsonb вида
 * `{"ru": "Ботинки", "en": "Boots"}`, а не строкой. Причина не в
 * будущем интерфейсе на английском, а в том, что продукт целится
 * в другие страны: там прокат заведёт свои названия, и это ДАННЫЕ
 * тенанта, которые нельзя перевести ни файлом локализации, ни нами.
 *
 * ⚠️ Разрешение локали живёт ЗДЕСЬ, а не разбросано по запросам.
 * Первая версия писала `name?.ru ?? code` в каждом месте, где название
 * доставалось из БД, — и когда локаль перестанет быть русской, найти
 * все такие места будет нечем: `?.ru` не грепается как ошибка, он
 * выглядит как рабочий код.
 *
 * ⚠️ Падение на код варианта («sb-147»), а не на пустую строку:
 * сотрудник должен увидеть хоть что-то опознаваемое, если перевод
 * забыли завести. Пустая ячейка в списке — это позиция, которую нельзя
 * выдать, потому что непонятно, что это.
 */
export type I18nField = Record<string, string> | string | null | undefined

/**
 * Значение поля на нужном языке.
 *
 * Порядок: запрошенная локаль → русская → первая заполненная →
 * запасное значение. Каждый шаг — про реальный случай: прокат завёл
 * только русское название; завёл только английское; не завёл ничего.
 */
export function localized(field: I18nField, locale = 'ru', fallback = ''): string {
  if (typeof field === 'string') return field || fallback
  if (!field) return fallback

  const exact = field[locale]
  if (exact) return exact

  const ru = field.ru
  if (ru) return ru

  const first = Object.values(field).find((v) => typeof v === 'string' && v)
  return first ?? fallback
}
