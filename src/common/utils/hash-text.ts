/**
 * Хеш текста для подписи (ПЭП).
 *
 * ⚠️ Реализация ОДНА на весь проект, и живёт в shared именно поэтому.
 * Подпись клиента доказывает что-то, только пока текст и его хеш
 * считаются одинаково везде: в момент показа оферты, в момент
 * подписания и при разборе спора через год. Вторая реализация
 * разошлась бы с первой на первой же правке — достаточно, чтобы одна
 * начала нормализовать переводы строк, и все прошлые подписи
 * перестанут сходиться.
 *
 * ⚠️ Хеш считается от ТОГО ЖЕ текста, что показан клиенту. Показывать
 * одно, а хешировать другое (например, «очищенную» версию) — значит
 * получить подпись, которая ничего не доказывает.
 */
import { createHash } from 'node:crypto'

export function hashText(text: string): string {
  return createHash('sha256').update(text, 'utf8').digest('hex')
}
