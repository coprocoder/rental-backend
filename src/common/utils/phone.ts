/**
 * Телефон РФ: маска, разбор и проверка.
 *
 * ⚠️ В shared, а не в компоненте: тот же номер проверяет сервер
 * (../rental-docs/docs/04-тз/10-бэкенд/16-уведомления.md). Клиентская проверка —
 * удобство, серверная — истина; расходиться им нельзя.
 *
 * ⚠️ Своя маска, а не libphonenumber-js: та тянет 1100+ строк, таблицу
 * стран и выпадающий список, а прокату нужен один формат. Идея переноса
 * каретки — известный приём: считать значащие цифры до каретки,
 * а не позицию в строке.
 *
 * ⚠️ ХРАНИТСЯ номер в канонической форме `+7XXXXXXXXXX`, а маска —
 * только для показа. Форматированный номер в БД сломал бы поиск
 * по телефону и сравнение «тот же клиент».
 */

/** Только цифры. */
function digits(v: string): string {
  return v.replace(/\D/g, '')
}

/**
 * Приводит ввод к десяти цифрам национального номера.
 *
 * Принимает и «8», и «+7», и «7» в начале: люди пишут все три, и отвергать
 * привычную запись значит терять заказ на ровном месте.
 */
export function normalizePhone(input: string): string {
  let d = digits(input)
  if (d.startsWith('8')) d = d.slice(1)
  else if (d.startsWith('7')) d = d.slice(1)
  return d.slice(0, 10)
}

/** Каноническая форма для БД и отправки: `+7XXXXXXXXXX`. */
/**
 * Схема валибота для телефона на границе API.
 *
 * ⚠️ ПРИВОДИТ к канонической форме, а не только проверяет: иначе
 * `+7 999 123-45-67` и `89991234567` создают ДВУХ клиентов, потому что
 * уникальный индекс (tenant_id, phone) их не связывает. Отсюда: счётчик
 * неявок и лимит активных броней обходятся сменой формата записи,
 * стойка не находит заказ по телефону, а выгрузка по 152-ФЗ возвращает
 * не все данные субъекта — это уже юридическое последствие.
 *
 * ⚠️ Нормализация именно НА ГРАНИЦЕ, один раз: дальше по коду ходит
 * уже канонический номер, и забыть про неё в новой ветке нельзя.
 * Раньше `shared/phone` не импортировался сервером вовсе — приводила
 * номер только форма бронирования, а стойка, лист ожидания и walk-in
 * писали в базу то, что пришло.
 */
export function canonicalPhone(input: string): string {
  // ⚠️ Считаем цифры ДО обрезки, которую делает normalizePhone.
  // Она нужна маске ввода — та отбрасывает лишние нажатия на лету, —
  // но канону вредна: «р8987987987989» (13 цифр) обрезалось до десяти
  // и превращалось в валидный «+79879879879». То есть номер с лишними
  // цифрами не отвергался, а МОЛЧА становился другим номером.
  const all = digits(input)
  const body = all.startsWith('8') || all.startsWith('7') ? all.slice(1) : all
  if (body.length !== 10) return ''
  return `+7${body}`
}

/** `+7 999 123-45-67` — для показа в поле. */
export function formatPhone(input: string): string {
  const d = normalizePhone(input)
  if (!d) return ''
  let out = '+7'
  if (d.length > 0) out += ' ' + d.slice(0, 3)
  if (d.length > 3) out += ' ' + d.slice(3, 6)
  if (d.length > 6) out += '-' + d.slice(6, 8)
  if (d.length > 8) out += '-' + d.slice(8, 10)
  return out
}

/**
 * Валиден ли номер.
 *
 * ⚠️ Проверяем длину и код оператора, но не существование номера:
 * этого не знает никто, кроме оператора. Первая цифра национального
 * номера в РФ — 3..9 (9 — мобильные, 3–8 — географические и сервисные),
 * поэтому «0» и «1» отсекаем: это заведомая опечатка.
 */
export function isValidPhone(input: string): boolean {
  const d = normalizePhone(input)
  return d.length === 10 && /^[3-9]/.test(d)
}

/** Человеку — что именно не так. */
export function phoneError(input: string): string | null {
  const d = normalizePhone(input)
  if (d.length === 0) return null
  if (d.length < 10) return `Не хватает цифр: ${d.length} из 10`
  if (!/^[3-9]/.test(d)) return 'Номер начинается не с кода оператора'
  return null
}

/**
 * Новая позиция каретки после подстановки маски.
 *
 * ⚠️ Без этого каретка прыгает в конец при правке середины номера —
 * поле становится непригодным для исправления опечатки.
 *
 * @param raw       значение до форматирования
 * @param caret     позиция каретки в нём
 * @param formatted результат formatPhone
 */
export function caretAfterFormat(raw: string, caret: number, formatted: string): number {
  // Сколько значащих цифр стоит левее каретки.
  const before = digits(raw.slice(0, caret)).length
  if (before === 0) return formatted.length

  let seen = 0
  for (let i = 0; i < formatted.length; i++) {
    if (/\d/.test(formatted[i]!)) {
      // +7 в начале маски не входит в набранное пользователем.
      if (i > 1) seen++
      if (seen === before) return i + 1
    }
  }
  return formatted.length
}
