/**
 * Тема тенанта: ограниченный набор токенов (8A.4, 13.15).
 *
 * ⚠️ Произвольный CSS от тенанта НЕ ПРИНИМАЕТСЯ (25-дизайн-система.md).
 * Иначе получим сломанные виджеты и обращения в поддержку, где виноват
 * будет не прокат, а мы. Десять осмысленных параметров надёжнее полной
 * свободы.
 *
 * ⚠️ Белый список один на чтение и на запись. Пока он был написан
 * дважды — в каталоге и в админке, — сохранить можно было бы поле,
 * которое витрина потом молча игнорирует: прокат меняет цвет, ничего
 * не происходит, и он идёт в поддержку.
 *
 * ⚠️ В БД хранится HEX, никогда «сырые каналы» вида `11 107 94`.
 * С каналами модификатор прозрачности (bg-brand/50) молча даёт
 * полностью прозрачный цвет — без ошибки, просто невидимый элемент.
 */

/** Радиусы из короткого списка, а не любое число: иначе тенант введёт 40px и всё поплывёт. */
export const ALLOWED_RADII = [0, 8, 12, 16] as const

const THEME_COLOR_KEYS = ['brand', 'brandSubtle', 'bg', 'surface'] as const

/**
 * Оставляет только допустимые токены в допустимом формате.
 *
 * Значение неверного формата ОТБРАСЫВАЕТСЯ, а не исправляется:
 * «почти чёрный вместо белого» хуже, чем цвет по умолчанию, потому что
 * выглядит как решение системы, а не как незаполненное поле.
 */
export function pickTheme(theme: Record<string, unknown> | null | undefined): Record<string, string> {
  const out: Record<string, string> = {}
  if (!theme) return out

  const hex = /^#[0-9a-f]{6}$/i
  for (const k of THEME_COLOR_KEYS) {
    const val = theme[k]
    if (typeof val === 'string' && hex.test(val)) out[k] = val
  }

  // ⚠️ parseInt, а не Number: функция — единый белый список на чтение
  // И на запись, а пишет она строку «16px». Number('16px') это NaN,
  // поэтому первое сохранение проходило, а следующее теряло радиус
  // навсегда — тенант ставил скругление, возвращался к настройкам,
  // и оно молча слетало на дефолт. Собственный вывод обязан быть
  // допустимым входом.
  const radius = Number.parseInt(String(theme.radius ?? ''), 10)
  if (ALLOWED_RADII.includes(radius as typeof ALLOWED_RADII[number])) {
    out.radius = `${radius}px`
  }

  // Логотип — только по относительному пути в нашем хранилище.
  // ⚠️ Не любой URL: чужая ссылка в теме — это и внешний запрос из
  // виджета при строгом CSP (не отрисуется), и канал отслеживания
  // клиентов проката третьей стороной.
  if (typeof theme.logoUrl === 'string' && /^\/[\w\-./]+$/.test(theme.logoUrl)) {
    out.logoUrl = theme.logoUrl
  }

  return out
}

/**
 * Тема → значения CSS-переменных.
 *
 * ⚠️ Одна функция на витрину и на предпросмотр в админке (13.15).
 * Пока отображение было написано дважды, предпросмотр и витрина могли
 * разойтись — а обещание экрана темы ровно в том, что показанное
 * и есть то, что увидит клиент.
 *
 * ⚠️ Переопределяются ЗНАЧЕНИЯ существующих ключей палитры, новых
 * не заводится: производные (--brand-hover, --brand-subtle, --brand-fg)
 * пересчитаются сами, потому что объявлены на `*`. Задавать их руками
 * значило бы показывать не то, что получится на самом деле.
 *
 * ⚠️ Применять ТОЛЬКО инлайновым стилем, не отдельным <style>. Тег
 * имеет ту же специфичность, что и palette.css (:root против :root),
 * а порядок в <head> не гарантирован — дефолт оказывался ниже и затирал
 * тему. Симптом обманчивый: до первого взаимодействия форма зелёная,
 * после перерисовки — фирменная.
 *
 * @param theme уже прошедшая pickTheme тема; radius приходит с «px»
 */
export function themeVars(theme: Record<string, string | undefined> | null | undefined): Record<string, string> {
  const t = theme ?? {}
  const out: Record<string, string> = {}
  if (t.brand) out['--brand-raw'] = t.brand
  if (t.brandSubtle) out['--brand-subtle'] = t.brandSubtle
  if (t.bg) out['--bg-page'] = t.bg
  if (t.surface) out['--bg-surface'] = t.surface
  if (t.radius) {
    out['--radius'] = t.radius
    // Крупный радиус на 4px больше базового — соотношение из дизайн-системы.
    out['--radius-lg'] = `${Number.parseInt(t.radius, 10) + 4}px`
  }
  return out
}
