/**
 * Проверка почты для интерфейса.
 *
 * ⚠️ Клиентская проверка — удобство, не истина: на сервере то же поле
 * проверяет valibot (`v.email()`), и он остаётся последним словом.
 * Здесь задача другая — сказать человеку, что не так, ДО отправки,
 * а не показать «не удалось оформить заказ» после.
 *
 * ⚠️ Намеренно НЕ пытаемся повторить RFC 5322: полная грамматика
 * допускает адреса, которые в жизни не встречаются, а строгая регулярка
 * отвергает валидные (апостроф в ирландских фамилиях, длинные новые
 * домены). Проверяем форму «есть имя, @, домен с точкой» и не мешаем
 * человеку, если адрес необычный — доставку всё равно проверит письмо.
 */

export function isValidEmail(input: string): boolean {
  const v = input.trim()
  if (!v) return false
  if (v.length > 254) return false
  // Одна @, непустые части, в домене точка не с краю.
  return /^[^\s@]+@[^\s@.]+(\.[^\s@.]+)+$/.test(v)
}

/** Человеку — что именно не так. */
export function emailError(input: string): string | null {
  const v = input.trim()
  if (!v) return null
  if (!v.includes('@')) return 'В адресе нет @'
  if (v.split('@').length > 2) return 'В адресе больше одной @'
  const [name, domain] = v.split('@')
  if (!name) return 'Перед @ пусто'
  if (!domain) return 'После @ пусто'
  if (!domain.includes('.')) return 'В домене нет точки'
  if (!isValidEmail(v)) return 'Похоже на опечатку'
  return null
}
