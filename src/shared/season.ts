/**
 * Сезонность категории — данными, а не кодом.
 *
 * Обещание ТЗ (../rental-docs/docs/04-тз/00-общее/03-домен.md): «добавить сапборды на лето»
 * — это завести категорию, ноль изменений в коде. Значит период
 * активности живёт на категории и проверяется одинаково везде: в
 * каталоге, при создании заказа и в отчётах.
 *
 * ⚠️ Без этого поля происходили четыре вещи, каждая плохая:
 *   каталог в сентябре предлагал сноуборды и сапборды одновременно —
 *   выбор, которого у проката фактически нет;
 *   отчёт упущенного спроса смешивал летний отказ по сноуборду с
 *   зимним, и «доложить в 155–159» строилось на запросах, которых
 *   в сезон не будет;
 *   загрузка сапбордов зимой считалась как 0% при существующей ёмкости,
 *   и отчёт советовал «продать часть», хотя они просто ждут лета;
 *   смешанный заказ «сноуборд + сапборд на 15 января» проходил без
 *   единой проверки.
 *
 * ⚠️ Период задаётся МЕСЯЦАМИ, а не датами: сезон повторяется каждый
 * год, и daterange пришлось бы перезаводить ежегодно. Зима 11→4
 * переходит через Новый год — это нормальный случай, а не крайний.
 *
 * ⚠️ Проверяется дата АРЕНДЫ, а не дата визита: клиент в апреле
 * бронирует сапборд на июль — это законно, и категория должна быть
 * доступна. Условие всегда против from/to заказа.
 *
 * ⚠️ Сезон филиала — НЕЗАВИСИМАЯ ось (../rental-docs/docs/04-тз/10-бэкенд/18-время...):
 * филиал закрыт целиком, а категория неактивна при работающем филиале.
 * Функция одна, применяется к обоим, но смешивать их нельзя.
 *
 * SQL-двойник — season_month_active() в drizzle/manual/0011. Тест
 * проверяет, что обе реализации согласны на всех 12×12×12 комбинациях.
 */

interface Season {
  /** Первый месяц сезона, 1–12. null — круглый год. */
  fromMonth: number | null
  /** Последний месяц сезона включительно, 1–12. null — круглый год. */
  toMonth: number | null
}

/**
 * Активен ли месяц в сезоне.
 *
 * Оба null — круглый год. Один null — тоже круглый год: половина
 * границы бессмысленна, и трактовать её как ошибку значило бы закрыть
 * категорию из-за недозаполненной формы, а система должна работать
 * при небрежном заполнении данных.
 */
export function monthInSeason(month: number, season: Season): boolean {
  const { fromMonth: f, toMonth: t } = season
  if (f == null || t == null) return true

  // Внутри одного года: 5→9.
  if (f <= t) return month >= f && month <= t
  // Через Новый год: 11→4 означает 11, 12, 1, 2, 3, 4.
  return month >= f || month <= t
}

/**
 * Месяц даты в поясе филиала.
 *
 * ⚠️ Через Intl, а не getMonth(): аренда 1 мая в 00:30 по Красноярску —
 * это ещё 30 апреля по UTC, и getMonth() отнёс бы её к апрелю.
 */
export function localMonth(d: Date, timezone: string): number {
  const s = new Intl.DateTimeFormat('en-CA', { timeZone: timezone, month: 'numeric' }).format(d)
  return Number(s)
}

/**
 * Активна ли категория на интервал аренды.
 *
 * ⚠️ Проверяется месяц НАЧАЛА, а не оба конца: аренда 30 апреля —
 * 2 мая для зимней категории 11→4 должна проходить. Клиент выбирает
 * дату начала, а хвост в два дня на стыке сезонов — не повод отказать.
 * Обратное (начало вне сезона, конец внутри) — отказ: 25 октября
 * сноуборд ещё не в сезоне, что бы ни было 1 ноября.
 */
export function seasonAllows(from: Date, season: Season, timezone: string): boolean {
  return monthInSeason(localMonth(from, timezone), season)
}

/** Читаемое описание сезона для интерфейса и отчёта. */
export function describeSeason(season: Season, locale = 'ru'): string {
  if (season.fromMonth == null || season.toMonth == null) {
    return locale === 'en' ? 'all year' : 'круглый год'
  }
  const names = locale === 'en'
    ? ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
    : ['янв', 'фев', 'мар', 'апр', 'май', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек']
  return `${names[season.fromMonth - 1]}–${names[season.toMonth - 1]}`
}
