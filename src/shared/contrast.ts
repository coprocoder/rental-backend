/**
 * Проверка контраста темы тенанта (13.15).
 *
 * ⚠️ Нужна не «для галочки по доступности». Прокат выбирает акцент по
 * вкусу — светло-жёлтый, салатовый, — и белый текст на нём перестаёт
 * читаться. Виджет при этом стоит на сайте проката и выглядит как его
 * собственный: испорченным окажется впечатление клиента о прокате,
 * а не о нас. Поэтому проверка идёт ДО сохранения, с показом результата.
 *
 * ⚠️ Считается по WCAG 2.1: относительная яркость с гамма-коррекцией,
 * отношение (L1 + 0.05) / (L2 + 0.05). Порог 4.5:1 для обычного текста
 * и 3:1 для крупного — числа из стандарта, не из головы.
 *
 * ⚠️ Проверка НЕ ЗАПРЕЩАЕТ сохранение. Прокат вправе выбрать свой
 * фирменный цвет, даже неудачный, — а система обязана предупредить
 * и показать, как это выглядит. Запрет здесь означал бы, что владелец
 * не может поставить свой логотипный цвет и уходит к конкуренту.
 */

/** hex → каналы 0–255. Принимает #rgb и #rrggbb. */
export function hexToRgb(hex: string): [number, number, number] | null {
  const h = hex.trim().replace(/^#/, '')
  if (/^[0-9a-f]{3}$/i.test(h)) {
    return [
      parseInt(h[0]! + h[0]!, 16),
      parseInt(h[1]! + h[1]!, 16),
      parseInt(h[2]! + h[2]!, 16),
    ]
  }
  if (/^[0-9a-f]{6}$/i.test(h)) {
    return [
      parseInt(h.slice(0, 2), 16),
      parseInt(h.slice(2, 4), 16),
      parseInt(h.slice(4, 6), 16),
    ]
  }
  return null
}

/**
 * Относительная яркость по WCAG.
 *
 * ⚠️ С гамма-коррекцией, а не просто среднее каналов: восприятие
 * яркости нелинейно, и «среднее» ошибается больше всего именно там,
 * где важно — на насыщенных цветах вроде фирменного зелёного.
 */
function luminance([r, g, b]: [number, number, number]): number {
  const ch = (v: number) => {
    const s = v / 255
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
  }
  return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)
}

/** Отношение контраста двух цветов, от 1 до 21. */
export function contrastRatio(a: string, b: string): number | null {
  const ca = hexToRgb(a)
  const cb = hexToRgb(b)
  if (!ca || !cb) return null
  const la = luminance(ca)
  const lb = luminance(cb)
  const [hi, lo] = la > lb ? [la, lb] : [lb, la]
  return (hi + 0.05) / (lo + 0.05)
}

interface ContrastVerdict {
  /** Контраст с тем цветом текста, который система выберет сама. */
  ratio: number
  /** Каким будет текст на этом фоне: автоконтраст --brand-fg. */
  textColor: 'white' | 'dark'
  /** Проходит для обычного текста (4.5:1). */
  passesText: boolean
  /** Проходит для крупного текста и кнопок (3:1). */
  passesLarge: boolean
  /**
   * Контраст именно с БЕЛЫМ текстом.
   *
   * ⚠️ Считается отдельно, и это не избыточность. Автоконтраст
   * (--brand-fg) выбирает белый или тёмный относительным синтаксисом
   * цвета, который поддержан примерно у 91% браузеров; у остальных
   * работает запасное значение — БЕЛЫЙ. То есть на светлом акценте
   * часть клиентов увидит ровно то, о чём предупреждает эта строка,
   * даже когда «система выберет тёмный».
   */
  whiteRatio: number
  whitePassesText: boolean
  advice: string
  /** Чем это грозит, если автоконтраст не сработает. Пусто — если не грозит. */
  fallbackWarning: string | null
}

/**
 * Какой текст класть на этот фон и читается ли он.
 *
 * ⚠️ Возвращает не только «лучший из белого и тёмного». Первая версия
 * возвращала именно его — и предупреждение стало бесполезным: у любого
 * цвета хоть один из двух вариантов проходит, худший возможный случай
 * даёт 4.23:1, и проверка не срабатывала практически никогда. То есть
 * ровно тот сценарий из ТЗ — «светло-жёлтый акцент с белым текстом» —
 * она пропускала, потому что мысленно подставляла тёмный текст.
 *
 * Поэтому считаются оба варианта: выбранный системой и белый как
 * запасной. Предупреждает второй.
 */
export function verdictOn(background: string): ContrastVerdict | null {
  const white = contrastRatio(background, '#ffffff')
  const black = contrastRatio(background, '#101820')
  if (white === null || black === null) return null

  const useWhite = white >= black
  const ratio = Math.max(white, black)

  return {
    ratio,
    textColor: useWhite ? 'white' : 'dark',
    passesText: ratio >= 4.5,
    passesLarge: ratio >= 3,
    whiteRatio: white,
    whitePassesText: white >= 4.5,
    advice: ratio >= 4.5
      ? `Читается: текст будет ${useWhite ? 'белым' : 'тёмным'}, контраст ${ratio.toFixed(1)}:1.`
      : ratio >= 3
        ? `Годится только для крупного текста и кнопок: контраст ${ratio.toFixed(1)}:1 при норме 4.5:1. Мелкие подписи на этом фоне читаться не будут.`
        : `Текст на этом фоне не читается: контраст ${ratio.toFixed(1)}:1 при норме 4.5:1. Возьмите цвет темнее или светлее — оттенок останется тем же.`,
    // Предупреждаем только когда система выбрала ТЁМНЫЙ: тогда белый —
    // это запасной вариант, и он окажется у части клиентов.
    fallbackWarning: !useWhite && white < 4.5
      ? `Цвет светлый: на нём читается только тёмный текст (${black.toFixed(1)}:1), а белый — нет (${white.toFixed(1)}:1). Система подставит тёмный, но примерно у каждого десятого клиента браузер старее нужного и покажет белый. На таком фоне надпись на кнопке у них пропадёт.`
      : null,
  }
}
