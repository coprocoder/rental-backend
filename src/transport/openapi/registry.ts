/**
 * Реестр схем ответов — единственный источник для OpenAPI и для типов
 * фронта.
 *
 * ⚠️ Зачем вообще. Схемы valibot описывали только ВХОДЫ: тела запросов
 * и query. Ответы были выведенными типами внутри обработчиков, то есть
 * снаружи репозитория их не существовало. После выноса бэкенда фронту
 * стало неоткуда выводить тип ответа — там выключили `noImplicitAny`
 * и получили 34 вызова `useApiFetch` без типа, где опечатка
 * `data.braches` не ловится компилятором (19.40).
 *
 * ⚠️ Схема ответа живёт РЯДОМ С РОУТОМ, в его контроллере, а не
 * в общем файле: иначе она разойдётся с обработчиком на первой же
 * правке, и документация начнёт лгать — ровно то, ради чего
 * генерация из кода и затевалась (19.42).
 *
 * ⚠️ Регистрация НЕ меняет поведение роута: Fastify здесь не
 * сериализует ответ по схеме. Схема — описание, а не фильтр. Включать
 * её как фильтр опасно: незадекларированное поле молча пропадёт
 * из ответа, и экран сломается без единой ошибки.
 */
import type { GenericSchema } from 'valibot'

export type Method = 'get' | 'post' | 'patch' | 'delete'

export interface RouteDoc {
  method: Method
  /** Путь как в контроллере: `/v1/public/catalog`, с `:param`. */
  path: string
  /** Краткое описание для документации. */
  summary: string
  /** Схема успешного ответа (200). */
  response: GenericSchema
  /**
   * Тип содержимого ответа, если это не JSON.
   *
   * ⚠️ Нужен потому, что два роута отдают НЕ JSON: выгрузка (`text/csv`)
   * и лист этикеток (`text/html`). Без этого поля они просто
   * отсутствовали в спецификации — «описаны все 37 роутов» было правдой
   * только про JSON-роуты, а внешний разработчик, читающий документ,
   * про выгрузку не узнавал вовсе.
   */
  contentType?: string
  /** Схема тела запроса, если есть. */
  body?: GenericSchema
  /** Схема query-параметров, если есть. */
  query?: GenericSchema
  /**
   * Контур доступа. Влияет только на документацию: публичный контур
   * выделяется для внешних разработчиков виджета.
   */
  scope: 'public' | 'staff'
}

const routes: RouteDoc[] = []

/** Объявляет схему ответа роута. Вызывается из его контроллера. */
export function documentRoute(doc: RouteDoc): void {
  routes.push(doc)
}

export function documentedRoutes(): readonly RouteDoc[] {
  return routes
}
