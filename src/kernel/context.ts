/**
 * Ctx — кто и в каком тенанте выполняет сценарий.
 *
 * ⚠️ Собирается ТРАНСПОРТОМ и передаётся в usecase готовым. Это граница,
 * ради которой всё затевалось: в сигнатуре usecase нет ни Request, ни
 * FastifyRequest, ни H3Event — и поэтому сценарий одинаково вызывается
 * из HTTP, из воркера, из теста и из будущего мобильного приложения
 * стойки. Как только сюда попадёт объект запроса, слой перестанет быть
 * переносимым, и это первое, что ломается на практике.
 */

/** Кто действует. Разные виды доступа — разные права, см. `plans/03-API.md`. */
export type Actor =
  /** Сотрудник с сессией: админка и стойка по правам. */
  | { kind: 'staff', staffId: string, role: string }
  /** Серверный ключ тенанта (`sk_…`): интеграции. */
  | { kind: 'apiKey', keyId: string }
  /**
   * Анонимный клиент витрины (`pk_…` или токен заказа).
   *
   * ⚠️ Токен заказа — не идентификатор: по нему действует
   * неаутентифицированный клиент, и доступ ограничен одним заказом.
   */
  | { kind: 'public' }

export interface Ctx {
  /**
   * ⚠️ ТОЛЬКО из сессии, ключа API или токена заказа — НИКОГДА из тела
   * запроса или query-параметра. RLS доверяет app.tenant_id, который
   * выставляет приложение; подмена одного поля дала бы доступ к чужим
   * данным (железное правило 10).
   */
  readonly tenantId: string
  readonly actor: Actor
  /** Сквозной идентификатор запроса: связывает запрос, событие и отправку. */
  readonly correlationId: string
}
