/**
 * Часы как зависимость.
 *
 * ⚠️ Не педантизм. Половина логики зависит от «сейчас»: снятие броней,
 * дедлайны подтверждения, сезоны, просрочка. Без подменяемых часов эти
 * сценарии тестируются только ожиданием — а «тест, который ждёт сутки»
 * не пишут вовсе.
 *
 * ⚠️ Уже стреляло: тест был зелёным утром и красным вечером, потому что
 * строил дни через toISOString() (UTC), а наличие считается в поясе
 * филиала. Подменяемые часы делают такой тест детерминированным.
 */
export type Clock = () => Date

export const systemClock: Clock = () => new Date()

/** Часы, остановленные на моменте. Для тестов. */
export function fixedClock(at: Date | string): Clock {
  const instant = typeof at === 'string' ? new Date(at) : at
  return () => new Date(instant)
}
