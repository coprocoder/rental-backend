-- Исправление области действия price_rule_no_overlap.
--
-- ⚠️ Найдено эталонным тестом движка цен: ограничение включало
-- rule_kind в ключ и потому запрещало два одновременных МОДИФИКАТОРА.
-- А алгоритм из ТЗ (docs/10-бэкенд/14-цены.md, «Разрешение конфликтов
-- правил») требует ровно обратного:
--
--   «студент (−250, stackable=false, priority 10) и после 17:00
--    (−30%, stackable=false, priority 20) — применится только
--    студенческий»
--
-- То есть оба правила ОБЯЗАНЫ существовать одновременно, а конфликт
-- разрешается приоритетом и флагом stackable в движке. Прайс пилота
-- содержит пересекающиеся модификаторы по определению — это его
-- нормальное состояние, а не ошибка данных.
--
-- Что действительно должно быть единственным — БАЗОВАЯ ставка: две
-- активные базовые цены на один вариант и дату означают неоднозначную
-- цену, и разрешать это нельзя. Поэтому ограничение сужается до
-- rule_kind = 'base'.
--
-- Идемпотентно.

DO $$
BEGIN
  ALTER TABLE price_rule DROP CONSTRAINT IF EXISTS price_rule_no_overlap;

  ALTER TABLE price_rule
    ADD CONSTRAINT price_rule_no_overlap
    EXCLUDE USING GIST (
      tenant_id  WITH =,
      variant_id WITH =,
      valid      WITH &&
    )
    -- Только базовые ставки: модификаторы пересекаются законно.
    WHERE (is_active AND archived_at IS NULL AND rule_kind = 'base');
END
$$;

COMMENT ON CONSTRAINT price_rule_no_overlap ON price_rule IS
  'Одна активная БАЗОВАЯ ставка на вариант и дату: две означали бы '
  'неоднозначную цену. Модификаторы под ограничение не попадают — '
  'они пересекаются законно (студент + после 17:00), а конфликт '
  'разрешается priority и stackable в движке цен.';
