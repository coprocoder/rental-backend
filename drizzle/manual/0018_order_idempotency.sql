-- Идемпотентность создания заказа — инвариантом БАЗЫ, а не кодом (19.35).
--
-- ⚠️ Железное правило 2: инварианты живут в БД. Защита была такой:
-- «SELECT по ключу → не нашёл → INSERT». Между чтением и вставкой
-- второй запрос успевает пройти ту же проверку, и оба вставляют заказ
-- с одним `Idempotency-Key`. Воспроизведено тестом на двух соединениях:
-- «вставок 2, коммитов 2» — два заказа вместо одного.
--
-- ⚠️ Чем это грозит на практике. Клиент нажимает «Забронировать»
-- дважды — на медленной связи обычное дело, а виджет ретраит сам.
-- Итог: два заказа, два удержания инвентаря, снаряжение снято со
-- склада в двойном объёме, и разбирать это человеку на стойке.
--
-- ⚠️ Уникальность В ПРЕДЕЛАХ ТЕНАНТА, а не глобальная: ключ генерирует
-- клиент, и два проката легко пришлют одинаковый. Глобальный индекс
-- отказал бы второму прокату в заказе — это утечка изоляции тенантов
-- через отказ в обслуживании.
--
-- ⚠️ ЧАСТИЧНЫЙ индекс (`WHERE ... IS NOT NULL`): заказы без ключа
-- приходят с витрины тысячами, и все они имеют `idemKey = NULL`.
-- В Postgres NULL не равен NULL, так что обычный уникальный индекс их
-- бы и не задел, — но частичный ещё и не хранит для них записи:
-- на 1500 заказах сезона это разница в размере индекса, а не в
-- корректности.
--
-- ⚠️ Индекс по ВЫРАЖЕНИЮ, а не по колонке: ключ лежит внутри
-- `price_breakdown` (снимок цены, железное правило 6), отдельной
-- колонки под него нет. Выносить его в колонку — отдельная правка со
-- своей миграцией и переносом данных; выражение закрывает гонку
-- сегодня и не меняет форму ответа API.
CREATE UNIQUE INDEX IF NOT EXISTS order_idem_key_uk
  ON rental_order (tenant_id, (price_breakdown ->> 'idemKey'))
  WHERE price_breakdown ->> 'idemKey' IS NOT NULL;
