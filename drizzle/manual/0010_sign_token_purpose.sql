-- Отдельное назначение токена для кода подписи договора.
--
-- ⚠️ Зачем: код ПЭП изначально писался с purpose = 'confirm', то есть
-- в то же назначение, что и ссылка подтверждения брони. Это два разных
-- механизма с разным смыслом и разным сроком жизни (ссылка живёт до
-- конца аренды плюс 30 дней, код — 15 минут), а главное — пометка
-- «использован» на одном могла бы задеть другой. Юридическое
-- доказательство подписи не должно зависеть от того, нажал ли клиент
-- ссылку подтверждения.
--
-- Идемпотентно: ADD VALUE IF NOT EXISTS доступен с Postgres 12.

ALTER TYPE order_token_purpose ADD VALUE IF NOT EXISTS 'sign';
