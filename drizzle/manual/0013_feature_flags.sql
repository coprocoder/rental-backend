-- Рубильники по тенанту, отдельно от тарифов (17.19).
--
-- ⚠️ Зачем ОТДЕЛЬНО от плана. Тариф отвечает на вопрос «за что заплачено»,
-- рубильник — на вопрос «что сейчас включено», и это разные вещи:
--   прокату надо выключить онлайн-бронирование на два дня инвентаризации
--     — он не менял тариф;
--   у одного тенанта ломается интеграция, и её надо погасить именно ему
--     — менять план из-за аварии нельзя;
--   новую функцию раскатывают на три проката из ста
--     — это не новый тариф.
-- Смешать их значит менять тарифный план ради временной операции,
-- а потом объяснять, почему в счёте другой план.
--
-- ⚠️ Значение NULL и отсутствие строки — РАЗНЫЕ вещи. Нет строки —
-- «решения нет, работает умолчание тарифа». Строка со значением —
-- «решено явно», и это переопределяет тариф в обе стороны: можно
-- и выключить оплаченное, и включить неоплаченное (пилот, компенсация
-- за аварию).
--
-- Идемпотентно.

CREATE TABLE IF NOT EXISTS tenant_flag (
  tenant_id  uuid NOT NULL REFERENCES tenant(id),
  -- Имя рубильника. Не enum: список меняется чаще, чем схема, а
  -- неизвестное имя просто не находит потребителя и ничего не ломает.
  flag       text NOT NULL,
  enabled    boolean NOT NULL,
  -- ⚠️ Причина обязательна, как у всех ручных вмешательств
  -- (железное правило №13): через месяц «почему у них выключено
  -- бронирование» иначе не выяснить.
  reason     text NOT NULL,
  -- Временный рубильник: до этого момента. NULL — бессрочно.
  -- Нужен для «выключили на инвентаризацию»: забыть включить обратно
  -- проще, чем кажется, и тогда прокат теряет заказы молча.
  until      timestamptz,
  set_by     uuid REFERENCES staff(id),
  set_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, flag),
  CONSTRAINT tenant_flag_reason_ck CHECK (length(btrim(reason)) >= 3)
);

-- ⚠️ Индекс по (tenant_id, until) БЕЗ предиката: now() в предикате
-- Postgres не принимает — предикат обязан быть IMMUTABLE, а now()
-- меняется каждую секунду, и индекс с ним пришлось бы перестраивать.
-- Отбор по сроку делает запрос, индекс лишь сужает до тенанта.
CREATE INDEX IF NOT EXISTS tenant_flag_lookup
  ON tenant_flag (tenant_id, until);

-- ⚠️ RLS НЕ включается намеренно, и это единственная такая таблица.
-- Рубильники ставит платформа, а не тенант: смысл в том, чтобы
-- поддержка могла погасить функцию у конкретного проката, в том числе
-- когда у самого проката всё «работает». Тенант их не читает и не
-- пишет — доступ только у рабочей роли и платформенного контура.
-- ⚠️ REVOKE именно У РОЛЕЙ, а не только у PUBLIC. В схеме заданы
-- DEFAULT PRIVILEGES (`rental_app=arwd`), поэтому новая таблица
-- получает права на запись АВТОМАТИЧЕСКИ, и `REVOKE … FROM PUBLIC`
-- их не снимает. Без этой строки прикладная роль может удалить
-- рубильник, поставленный поддержкой, — то есть тенант снимает
-- с себя ограничение сам, и весь смысл рубильника пропадает.
-- Тест «исключения из RLS не потеряли ограничение прав» это стережёт.
REVOKE ALL ON tenant_flag FROM PUBLIC, rental_app, rental_worker;
GRANT SELECT ON tenant_flag TO rental_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON tenant_flag TO rental_worker;

COMMENT ON TABLE tenant_flag IS
  'Рубильники функций по тенанту, отдельно от тарифа. Переопределяют '
  'умолчание плана в обе стороны. Ставит платформа, не тенант.';
